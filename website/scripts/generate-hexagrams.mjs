#!/usr/bin/env node
// Generates website/src/data/hexagrams.ts from the curated backend dataset.
// Only reproduces fields that exist in backend/data/hexagrams.json; it never
// invents commentary or interpretations.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..', '..');
const source = resolve(root, 'backend', 'data', 'hexagrams.json');
const target = resolve(root, 'website', 'src', 'data', 'hexagrams.ts');

const raw = JSON.parse(readFileSync(source, 'utf8'));
const list = Array.isArray(raw) ? raw : raw.hexagrams;

if (!Array.isArray(list) || list.length !== 64) {
  throw new Error('expected 64 hexagrams, got ' + (Array.isArray(list) ? list.length : typeof raw));
}

const records = list
  .slice()
  .sort((a, b) => a.wenwang_order - b.wenwang_order)
  .map((h) => ({
    order: h.wenwang_order,
    name: h.name,
    title: h.title,
    binary: h.binary_code,
    upper: { name: h.upper_trigram.name, symbol: h.upper_trigram.symbol, image: h.upper_trigram.image },
    lower: { name: h.lower_trigram.name, symbol: h.lower_trigram.symbol, image: h.lower_trigram.image },
    judgment: h.judgment,
  }));

const header = `// Generated by website/scripts/generate-hexagrams.mjs — do not edit by hand.
// Source: backend/data/hexagrams.json (原文本转录自维基文库《周易》; 见 backend/data/README.md)
export interface Trigram {
  /** 卦名，如 乾 */
  name: string;
  /** Unicode 卦符，如 ☰ */
  symbol: string;
  /** 卦象，如 天 */
  image: string;
}

export interface HexagramRecord {
  /** 文王卦序 1–64 */
  order: number;
  /** 单字卦名，如 乾 */
  name: string;
  /** 全名，如 乾为天 */
  title: string;
  /** 六爻二进制，自初爻至上爻，1 为阳 */
  binary: string;
  upper: Trigram;
  lower: Trigram;
  /** 卦辞原文（繁体，沿用转录字形） */
  judgment: string;
}

export const hexagrams: HexagramRecord[] = `;

writeFileSync(
  target,
  header + JSON.stringify(records, null, 2) + ';\n',
  'utf8',
);
console.log('wrote ' + target + ' (' + records.length + ' records)');
